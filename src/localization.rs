use serde::{Deserialize, Serialize};

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum Language {
    #[default]
    English,
    French,
    Spanish,
    German,
    Chinese,
    Japanese,
    Russian,
    Korean,
}

impl Language {
    pub const ALL: [Self; 8] = [
        Self::English,
        Self::French,
        Self::Spanish,
        Self::German,
        Self::Chinese,
        Self::Japanese,
        Self::Russian,
        Self::Korean,
    ];

    pub fn native_name(self) -> &'static str {
        match self {
            Self::English => "English",
            Self::French => "Français",
            Self::Spanish => "Español",
            Self::German => "Deutsch",
            Self::Chinese => "简体中文",
            Self::Japanese => "日本語",
            Self::Russian => "Русский",
            Self::Korean => "한국어",
        }
    }

    fn index(self) -> usize {
        match self {
            Self::English => 0,
            Self::French => 1,
            Self::Spanish => 2,
            Self::German => 3,
            Self::Chinese => 4,
            Self::Japanese => 5,
            Self::Russian => 6,
            Self::Korean => 7,
        }
    }
}

