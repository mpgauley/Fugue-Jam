pub fn tr(language: Language, english: &'static str) -> &'static str {
    if language == Language::English {
        return english;
    }
    TRANSLATIONS
        .iter()
        .find(|(source, _)| *source == english)
        .map(|(_, translations)| translations[language.index()])
        .unwrap_or(english)
}

#[cfg(test)]
mod tests {
    use super::{Language, tr};

    #[test]
    fn supported_languages_have_native_names_and_translated_navigation() {
        assert_eq!(Language::default(), Language::English);
        for language in Language::ALL {
            assert!(!language.native_name().is_empty());
            if language == Language::English {
                assert_eq!(tr(language, "Library"), "Library");
            } else {
                assert_ne!(tr(language, "Library"), "Library");
            }
        }
    }

    #[test]
    fn unknown_strings_fall_back_to_english() {
        assert_eq!(
            tr(Language::Japanese, "Untranslated label"),
            "Untranslated label"
        );
    }
}
